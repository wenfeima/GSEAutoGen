-- v1.7：每个专精出两条，名字上直接标 SOLO / AOE
-- （为什么不做运行时切换：见 Writer.lua 顶部注释，战斗中改安全按钮是暴雪红线）
ns.SOLO_SUFFIX = "_SOLO"
