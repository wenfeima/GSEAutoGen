--- 取序列名。isAoe 为真返回 AOE 版，否则单体版
function ns:SeqName(specID, isAoe)
    local base = ns.SEQ_NAME[specID] or ("AGS_SPEC" .. tostring(specID))
    return base .. (isAoe and ns.AOE_SUFFIX or ns.SOLO_SUFFIX)
end

